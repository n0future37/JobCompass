def work_scope(query):
    for name, aliases, anchors, normalized in SCOPES:
        if re.search(aliases, query, re.I):
            return name, re.compile(anchors, re.I), normalized
    return None, None, query


def work_anchor_matches(scope, anchor, text):
    if not anchor or not anchor.search(text):
        return False
    if scope in {
        "ai_application",
        "python",
        "java",
        "rag",
        "agent",
        "nlp",
        "software",
        "vision",
        "testing",
        "frontend",
        "data_engineering",
    }:
        if not re.search(
            r"开发|构建|搭建|实现|编写|训练|优化|部署|维护|调试|设计|评估|编码|测试|分析|实现|处理", text
        ):
            return False
    if scope == "finance" and re.search(r"(?:开发|设计|编写|维护).{0,30}(?:软件|系统|模块|接口)", text):
        # 财务系统开发不等于办理会计核算；真实操作账务仍允许。
        if not re.search(r"办理|审核.*(?:费用|报销)|凭证录入|纳税申报|登记.*账|往来对账", text):
            return False
    return True
